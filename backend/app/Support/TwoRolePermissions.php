    public static function seed(): void
    {
        app(PermissionRegistrar::class)->forgetCachedPermissions();
        DB::transaction(function (): void {
            $adminNames = array_values(array_unique(array_merge(self::ACCOUNTANT, self::ADMIN_ONLY)));
            foreach ($adminNames as $name) {
                Permission::findOrCreate($name, 'web');
            }
            app(PermissionRegistrar::class)->forgetCachedPermissions();

            $accountantPerms = Permission::whereIn('name', self::ACCOUNTANT)->where('guard_name', 'web')->get();
            $adminPerms = Permission::whereIn('name', $adminNames)->where('guard_name', 'web')->get();

            Role::findOrCreate('accountant', 'web')->syncPermissions($accountantPerms);
            Role::findOrCreate('admin', 'web')->syncPermissions($adminPerms);
            // No user assignments and no deletion or alteration of legacy roles.
        });
        app(PermissionRegistrar::class)->forgetCachedPermissions();
    }
